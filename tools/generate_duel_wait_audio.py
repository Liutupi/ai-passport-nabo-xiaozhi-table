"""Expose the exact existing NABO wooden-fish PCM to the browser prototype."""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'xiaozhi-esp32/main/boards/folotoy/ai-passport-nabo/nabo_muyu_sound.h'
body = source.read_text('utf-8').split('= {', 1)[1].split('}', 1)[0]
pcm = [int(value) for value in re.findall(r'-?\d+', body)]
assert len(pcm) == 1440 and all(-32768 <= value <= 32767 for value in pcm)
payload = {'sampleRate': 16000, 'gain': 1.25, 'pcm': pcm,
           'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest()}
target = ROOT / 'game-art/duel/prototype/assets/nabo_duel_wait.js'
target.write_text('// Generated by tools/generate_duel_wait_audio.py; same PCM as the firmware.\n'
                  + 'window.NABO_DUEL_WAIT_AUDIO = ' + json.dumps(payload, separators=(',', ':')) + ';\n', 'utf-8')
print(f'Wooden-fish prototype audio: {len(pcm)} samples / 16000 Hz / 90 ms')
