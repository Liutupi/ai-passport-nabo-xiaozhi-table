"""Regenerate the NABO board's subset fonts with lv_font_conv 1.5.3.

Source TTFs stay outside the repository; pass their paths explicitly:

    python tools/generate_fonts.py --converter path/to/lv_font_conv \
        --sans SourceHanSansCN-Medium.otf --archivo ArchivoBlack-Regular.ttf \
        --mono SpaceMono-Bold.ttf

The 16/18 px UI fonts keep every glyph of the previous subset and add any
non-ASCII character used by the board sources, so new UI text never renders
as missing glyphs. Source Han Sans has tall ascenders; line heights are
tightened after conversion so existing layouts keep their rhythm.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / 'xiaozhi-esp32/main/boards/folotoy/ai-passport-nabo'
POSTER_28 = ' !%&-./0123456789:?ABCDEFGHIJKLMNOPQRSTUVWXYZ'
POSTER_48 = '%0123456789ABCDEISV!'  # DIVE title letters included
FONTS = {
    'nabo_menu_font_16': ('sans', 16, 4),
    'nabo_ui_font_18': ('sans', 18, 4),
    'nabo_poster_font_28': ('archivo', 28, 4),
    'nabo_poster_font_48': ('archivo', 48, 4),
    'nabo_mono_font_12': ('mono', 12, 4),
    # NABO TABLE: 12 px for hints and labels, 24 px for a few big words.
    'nabo_table_font_12': ('sans', 12, 4),
    'nabo_table_font_24': ('sans', 24, 4),
    # NABO DUEL: the shout on the draw.
    'nabo_duel_font_56': ('sans', 56, 4),
}
TABLE_24 = '玩家 12345678获胜输了暂停开！谁是卧底出局平民胜利'
# NABO DUEL headlines (nabo_table_scene_duel.c) drawn with the 24 px font.
DUEL_24 = '邀你对决赢了这局抢跑慢一步都太急睡着？模样！下场对手准备……暂停认输离开信号断'
DUEL_56 = '拔！？抢跑'


def existing_menu_glyphs():
    """Code points already shipped in nabo_menu_font_16.c (sparse cmap)."""
    path = BOARD / 'nabo_menu_font_16.c'
    if not path.exists():
        return set()
    text = path.read_text('utf-8')
    found = set()
    for match in re.finditer(r'/\* U\+([0-9A-F]+) ', text):
        found.add(int(match.group(1), 16))
    return {c for c in found if c > 0x7e}


def table_glyphs():
    """Non-ASCII code points used by the NABO TABLE sources."""
    chars = set()
    for path in sorted(BOARD.glob('nabo_table_*.c')):
        # Generated fonts list their own glyphs in comments: never feed them back in.
        if not path.name.startswith('._') and not re.match(r'nabo_\w+_font_\d+\.c$', path.name):
            chars.update(ord(c) for c in path.read_text('utf-8') if ord(c) > 0x7e)
    return {c for c in chars if c < 0x2500 or 0x3000 <= c <= 0x9fff or 0xff00 <= c <= 0xffef}


def source_glyphs():
    chars = set()
    for path in sorted(BOARD.glob('*.[ch]')) + sorted(BOARD.glob('*.cc')):
        # The undercover word list is drawn only with the 24 px table font (see table_24_symbols).
        if path.name.startswith('._') or path.name in ('nabo_menu_font_16.c', 'nabo_ui_font_18.c', 'nabo_uc_words.c'):
            continue
        if re.match(r'nabo_\w+_font_\d+\.c$', path.name):   # generated fonts (their comments list glyphs)
            continue
        chars.update(ord(c) for c in path.read_text('utf-8') if ord(c) > 0x7e)
    # Box drawing / emoji never belong in the menu font.
    return {c for c in chars if c < 0x2500 or 0x3000 <= c <= 0x9fff or 0xff00 <= c <= 0xffef}


def table_24_symbols():
    """Big table words plus every character of the who-is-the-undercover word list."""
    from generate_uc_words import word_chars
    return ''.join(sorted(set(TABLE_24) | set(DUEL_24) | set(word_chars())))


LINE_HEIGHT = {'nabo_menu_font_16': (19, 4), 'nabo_ui_font_18': (22, 5)}


def convert(converter, font, name, size, bpp, ascii_range=None, symbols=''):
    output = BOARD / f'{name}.c'
    command = [converter, '--font', str(font), '--size', str(size), '--bpp', str(bpp),
               '--format', 'lvgl', '--no-compress', '--no-kerning',
               '--lv-font-name', name, '--lv-include', 'lvgl.h', '--output', str(output)]
    if ascii_range:
        command[5:5] = ['--range', ascii_range]
    if symbols:
        command[5:5] = ['--symbols', symbols]
    subprocess.run(command, check=True)
    source = re.sub(r' \* Opts:.*', f' * Generated by tools/generate_fonts.py from {Path(font).name}.',
                    output.read_text('utf-8'))
    if name in LINE_HEIGHT:
        height, base = LINE_HEIGHT[name]
        source = re.sub(r'\.line_height = \d+,', f'.line_height = {height},', source)
        source = re.sub(r'\.base_line = \d+,', f'.base_line = {base},', source)
    output.write_text(source, 'utf-8')
    return hashlib.sha256(output.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--converter', required=True)
    parser.add_argument('--sans', type=Path, required=True)
    parser.add_argument('--archivo', type=Path, required=True)
    parser.add_argument('--mono', type=Path, required=True)
    args = parser.parse_args()
    version = subprocess.check_output([args.converter, '--version'], text=True).strip()
    if version != '1.5.3':
        parser.error('lv_font_conv 1.5.3 required, found ' + version)
    sources = {'sans': args.sans, 'archivo': args.archivo, 'mono': args.mono}
    menu = ''.join(chr(c) for c in sorted(existing_menu_glyphs() | source_glyphs()))
    metadata = {'converter': 'lv_font_conv ' + version, 'fonts': {}}
    for name, (source, size, bpp) in FONTS.items():
        font = sources[source]
        if name in LINE_HEIGHT:
            digest = convert(args.converter, font, name, size, bpp, '0x20-0x7E', menu)
            symbols = menu
        elif name == 'nabo_table_font_12':
            symbols = ''.join(chr(c) for c in sorted(table_glyphs()))
            digest = convert(args.converter, font, name, size, bpp, '0x20-0x7E', symbols)
        elif name == 'nabo_table_font_24':
            symbols = table_24_symbols()
            digest = convert(args.converter, font, name, size, bpp, None, symbols)
        elif name == 'nabo_duel_font_56':
            symbols = DUEL_56
            digest = convert(args.converter, font, name, size, bpp, None, symbols)
        elif name == 'nabo_mono_font_12':
            digest = convert(args.converter, font, name, size, bpp, '0x20-0x7E')
            symbols = 'ASCII'
        else:
            symbols = POSTER_28 if size == 28 else POSTER_48
            digest = convert(args.converter, font, name, size, bpp, None, symbols)
        metadata['fonts'][name] = {
            'source': font.name, 'source_sha256': hashlib.sha256(font.read_bytes()).hexdigest(),
            'pixels': size, 'bpp': bpp, 'symbols': symbols, 'output_sha256': digest}
    (ROOT / 'game-art/fonts.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n', 'utf-8')
    print(f'Generated UI fonts with {len(menu)} non-ASCII glyphs and 3 display fonts')


if __name__ == '__main__':
    main()
