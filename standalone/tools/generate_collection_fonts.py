"""Generate collection-only UI fonts with lv_font_conv 1.5.3 and Source Han Sans.

The source font and converter are explicit build inputs and are not copied into firmware.
The original table/DIVE fonts stay unchanged.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--node', default='node')
    ap.add_argument('--converter', required=True, type=Path)
    ap.add_argument('--font', required=True, type=Path)
    args = ap.parse_args()
    version = subprocess.check_output([args.node, str(args.converter), '--version'], text=True).strip()
    if version != '1.5.3':
        raise ValueError('lv_font_conv 1.5.3 required')
    symbols = ''.join(sorted({c for c in (ROOT/'main/collection_ui.c').read_text('utf-8') if ord(c) > 127}))
    metadata = {'converter': 'lv_font_conv ' + version, 'font': args.font.name,
                'font_sha256': hashlib.sha256(args.font.read_bytes()).hexdigest(), 'symbols': symbols, 'outputs': {}}
    for size in (12, 16, 18):
        name = f'collection_font_{size}'
        out = ROOT/'main'/f'{name}.c'
        command = [args.node, str(args.converter), '--font', str(args.font), '--size', str(size),
                   '--bpp', '4', '--range', '0x20-0x7E', '--symbols', symbols, '--format', 'lvgl',
                   '--no-compress', '--no-kerning', '--lv-font-name', name, '--lv-include', 'lvgl.h', '--output', str(out)]
        subprocess.run(command, check=True)
        source = re.sub(r' \* Opts:.*', ' * Generated by firmware/tools/generate_collection_fonts.py (Source Han Sans).', out.read_text('utf-8'))
        height, baseline = {12: (15, 3), 16: (19, 4), 18: (22, 5)}[size]
        source = re.sub(r'\.line_height = \d+,', f'.line_height = {height},', source)
        source = re.sub(r'\.base_line = \d+,', f'.base_line = {baseline},', source)
        out.write_text(source.rstrip() + '\n', 'utf-8')
        metadata['outputs'][name] = hashlib.sha256(out.read_bytes()).hexdigest()
    (ROOT/'tools/collection-fonts.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2)+'\n', 'utf-8')

if __name__ == '__main__':
    main()
